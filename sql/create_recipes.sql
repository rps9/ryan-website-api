CREATE TABLE IF NOT EXISTS recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    description TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000),
    servings SMALLINT NOT NULL DEFAULT 1 CHECK (servings BETWEEN 1 AND 100),
    ingredients JSONB NOT NULL CHECK (jsonb_typeof(ingredients) = 'array'),
    steps JSONB NOT NULL CHECK (jsonb_typeof(steps) = 'array'),
    optimization_notes JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(optimization_notes) = 'array'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS recipes_user_updated_idx
    ON recipes (user_id, updated_at DESC);
